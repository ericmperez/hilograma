const unique = new Map<string, [string, string, string]>()
for (const row of RAW) {
  if (!unique.has(row[0])) unique.set(row[0], row)
}

export const DMC_COLORS: DmcColor[] = [...unique.values()].map(([code, name, hex]) => {
  const { r, g, b } = hexToRgb(hex)
  return { code, name, hex, r, g, b }
})

const LABS: Lab[] = DMC_COLORS.map((color) => rgbToLab(color.r, color.g, color.b))

export function nearestDmc(r: number, g: number, b: number, palette = DMC_COLORS): DmcColor {
  const lab = rgbToLab(r, g, b)
  let best = palette[0]
  let bestDist = Infinity
  const labs = palette === DMC_COLORS ? LABS : palette.map((c) => rgbToLab(c.r, c.g, c.b))
  for (let i = 0; i < palette.length; i++) {
    const dist = labDistance(lab, labs[i])
    if (dist < bestDist) {
      bestDist = dist
      best = palette[i]
    }
  }
  return best
}

export function nearestUnusedDmc(
  r: number,
  g: number,
  b: number,
  used: Set<string>,
): DmcColor {
  const lab = rgbToLab(r, g, b)
  let best = DMC_COLORS[0]
  let bestDist = Infinity
  for (let i = 0; i < DMC_COLORS.length; i++) {
    const color = DMC_COLORS[i]
    if (used.has(color.code) && used.size < DMC_COLORS.length) continue
    const dist = labDistance(lab, LABS[i])
    if (dist < bestDist) {
      bestDist = dist
      best = color
    }
  }
  return best
}
